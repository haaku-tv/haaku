// Command openapi generates the OpenAPI 3.1 specification for trakt-api from
// the code-first route registry, and verifies that the checked-in spec is
// fresh.
//
// It exists so generation is an explicit, reproducible step instead of a side
// effect of starting the API server. The server used to rewrite openapi.yaml
// into the working tree on every boot, which dropped unrelated spec diffs into
// innocent PRs. See issue #15.
//
// Usage:
//
//	go run ./cmd/openapi            # regenerate openapi.yaml
//	go run ./cmd/openapi -check     # verify freshness + route inventory; exit 1 on drift
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"

	"trakt-api/internal/httpapi"
	"trakt-api/internal/openapi"

	"github.com/gofiber/fiber/v2"
)

func main() {
	out := flag.String("o", "openapi.yaml", "path to write the generated spec to")
	check := flag.Bool("check", false,
		"verify the on-disk spec matches the registry (freshness and route inventory); exit non-zero on drift")
	flag.Parse()

	// Pin the generation environment. The committed spec documents the full v1
	// surface, including routes the server registers only outside production
	// (for example /v1/dev/clerk-webhook-simulate is gated on APP_ENV). Without
	// this the generated bytes would depend on the caller's environment and the
	// freshness check would be flaky.
	if err := os.Setenv("APP_ENV", "development"); err != nil {
		fatal(err)
	}

	// Populate the registry exactly as the server does — same code path, so the
	// spec cannot drift from what the router actually serves.
	httpapi.RegisterRoutes(fiber.New())

	if *check {
		os.Exit(runCheck(*out))
	}

	if err := openapi.GenerateYAML(*out); err != nil {
		fatal(err)
	}
	fmt.Printf("wrote %s (%d operations)\n", *out, len(openapi.RegistryInventory()))
}

// runCheck returns the process exit code: 0 when the on-disk spec is fresh and
// its route inventory matches the registry, 1 otherwise.
func runCheck(path string) int {
	fresh, err := openapi.GenerateYAMLBytes()
	if err != nil {
		fatal(err)
	}

	onDisk, err := os.ReadFile(path)
	if err != nil {
		fmt.Fprintf(os.Stderr, "cannot read %s: %v\n", path, err)
		return 1
	}

	status := 0

	if !bytes.Equal(fresh, onDisk) {
		fmt.Fprintf(os.Stderr,
			"%s is stale: regenerating it produces different bytes.\n"+
				"Run `make api-spec` and commit the result.\n", path)
		status = 1
	}

	spec, err := openapi.SpecInventory(onDisk)
	if err != nil {
		fmt.Fprintf(os.Stderr, "cannot parse %s: %v\n", path, err)
		return 1
	}
	missing, extra := openapi.DiffInventory(openapi.RegistryInventory(), spec)
	if len(missing) > 0 {
		fmt.Fprintf(os.Stderr,
			"%d registered route(s) missing from %s:%s\n",
			len(missing), path, openapi.FormatRouteList(missing))
		status = 1
	}
	if len(extra) > 0 {
		fmt.Fprintf(os.Stderr,
			"%d route(s) in %s with no registered handler:%s\n",
			len(extra), path, openapi.FormatRouteList(extra))
		status = 1
	}

	if status == 0 {
		fmt.Printf("%s is fresh; route inventory matches the registry\n", path)
	}
	return status
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
