import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

// The generated client is committed, and `pnpm build` type-checks against it, so
// it must stay in step with the contract. These tests fail loudly when the file
// is missing, hand-edited, or stale relative to openapi.yaml.
const schemaSource = readFileSync(
  fileURLToPath(new URL('./generated/schema.ts', import.meta.url)),
  'utf8'
)
const contractSource = readFileSync(
  fileURLToPath(new URL('../../../openapi.yaml', import.meta.url)),
  'utf8'
)

/** Path keys of the `paths` interface emitted by openapi-typescript. */
function schemaPaths(src: string): Set<string> {
  const paths = new Set<string>()
  let inPaths = false
  for (const line of src.split('\n')) {
    if (/^\S/.test(line)) {
      inPaths = /^export interface paths \{/.test(line)
      continue
    }
    if (!inPaths) continue
    const match = /^ {4}"(\/[^"]+)":\s*\{/.exec(line)
    if (match) paths.add(match[1])
  }
  return paths
}

/** Top-level path keys of the contract's `paths:` mapping (4-space indent). */
function contractPaths(src: string): Set<string> {
  const paths = new Set<string>()
  let inPaths = false
  for (const line of src.split('\n')) {
    if (/^\S/.test(line)) {
      inPaths = /^paths:\s*$/.test(line)
      continue
    }
    if (!inPaths) continue
    const match = /^ {4}"?(\/[^":]*)"?:\s*$/.exec(line)
    if (match) paths.add(match[1])
  }
  return paths
}

describe('generated API schema wiring', () => {
  it('is openapi-typescript output rather than a hand-written file', () => {
    expect(schemaSource).toContain('auto-generated by openapi-typescript')
    expect(schemaSource).toContain('export interface paths')
  })

  it('covers exactly the paths declared in openapi.yaml', () => {
    const schema = schemaPaths(schemaSource)
    const contract = contractPaths(contractSource)

    // Guard against the parser silently matching nothing.
    expect(schema.size).toBeGreaterThan(100)
    expect(contract.size).toBeGreaterThan(100)

    // Symmetric diff so a failure names the paths that drifted.
    const missingFromSchema = [...contract].filter((p) => !schema.has(p))
    const extraInSchema = [...schema].filter((p) => !contract.has(p))
    expect({ missingFromSchema, extraInSchema }).toEqual({
      missingFromSchema: [],
      extraInSchema: [],
    })
  })

  it('declares the paths the client actually calls', () => {
    const schema = schemaPaths(schemaSource)
    for (const path of [
      '/healthz',
      '/v1/movies/{id}',
      '/v1/shows/{id}',
      '/v1/search',
      '/v1/lists/{id}',
      '/v1/users/me/lists',
    ]) {
      expect(schema).toContain(path)
    }
  })
})
